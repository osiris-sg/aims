/**
 * Every customer and supplier should have a code.
 * (guru 2026-11-06: "this customer has no code mzke zsure all customer and
 *  suppliers have a code also" — Xero shows "LT Sambo (NSC106)", AIMS shows
 *  the bare name.)
 *
 * READ-ONLY by default. Nothing is written without --apply.
 *
 * WHY THEY ARE MISSING: Xero keeps a contact's code in Contact.AccountNumber,
 * and neither the one-off importer (xero-migration/01-contacts.ts) nor the
 * live pull (XeroSyncService.pullContacts) ever read that field — only name,
 * email, phone, address and tax number. So every contact that arrived from
 * Xero landed with a null code, while contacts created inside AIMS get one
 * generated by CustomersService/SuppliersService.
 *
 * Backfill order for each row with no code:
 *   1. Xero's AccountNumber, when the contact has one and it is still free.
 *   2. Otherwise a generated code, same scheme as the app:
 *      C<first A-Z0-9 of name><nnn>  /  S<…><nnn>, numbered MAX+1 per prefix.
 *
 * Usage (prod, report only):
 *   ./node_modules/.bin/dotenv -e .env.production -- \
 *     npx ts-node --transpile-only scripts/audit-contact-codes.ts
 *
 *   --org=<id>    default Biofuel
 *   --all-orgs    sweep every organization (generated codes only, no Xero)
 *   --no-xero     skip the Xero pull; generate codes only (costs no quota)
 *   --show=40     rows to list (default 20)
 *   --apply       write the codes
 */
import { createScriptPrisma, getXeroTokens, xeroGet, BIOFUEL_ORG_ID } from './xero-migration/_common';

const prisma = createScriptPrisma();
const arg = (k: string, d = '') =>
  process.argv.find((a) => a.startsWith(`--${k}=`))?.split('=').slice(1).join('=') ?? d;

const ORG = arg('org', BIOFUEL_ORG_ID);
const ALL_ORGS = process.argv.includes('--all-orgs');
const NO_XERO = process.argv.includes('--no-xero') || ALL_ORGS;
const SHOW = parseInt(arg('show', '20'), 10);
const APPLY = process.argv.includes('--apply');

/** Same prefix rule as CustomersService.generateCustomerCode — first A-Z0-9 of
 *  the name with accents folded, 'X' when the name has none (Chinese names). */
const prefixOf = (kind: 'C' | 'S', name: string) =>
  `${kind}${name?.normalize('NFD').toUpperCase().match(/[A-Z0-9]/)?.[0] || 'X'}`;

/** MAX(suffix)+1, never count+1 — count+1 regenerates an existing code the
 *  moment a letter group has a gap, and then every insert is a P2002. */
function nextCode(prefix: string, taken: Set<string>): string {
  const literal = prefix.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const re = new RegExp(`^${literal}(\\d+)$`);
  let max = 0;
  for (const c of Array.from(taken)) {
    const m = c.match(re);
    if (m) max = Math.max(max, parseInt(m[1], 10));
  }
  let n = max + 1;
  let code = `${prefix}${String(n).padStart(3, '0')}`;
  while (taken.has(code)) code = `${prefix}${String(++n).padStart(3, '0')}`;
  return code;
}

async function sweepOrg(organizationId: string, orgName: string, xeroByContactId: Map<string, string>) {
  const customers = await prisma.customer.findMany({
    where: { organizationId },
    select: { id: true, name: true, customerCode: true, xeroId: true },
    orderBy: { name: 'asc' },
  });
  const suppliers = await prisma.supplier.findMany({
    where: { organizationId },
    select: { id: true, name: true, supplierCode: true, xeroId: true },
    orderBy: { name: 'asc' },
  });

  const blank = (v: string | null) => !String(v ?? '').trim();
  const missingC = customers.filter((c) => blank(c.customerCode));
  const missingS = suppliers.filter((s) => blank(s.supplierCode));

  console.log(`\n${orgName}`);
  console.log('  ' + '-'.repeat(74));
  console.log(`  customers  ${String(customers.length).padStart(5)} total   ${String(missingC.length).padStart(5)} with NO code`);
  console.log(`  suppliers  ${String(suppliers.length).padStart(5)} total   ${String(missingS.length).padStart(5)} with NO code`);

  const takenC = new Set(customers.map((c) => String(c.customerCode ?? '').trim()).filter(Boolean));
  const takenS = new Set(suppliers.map((s) => String(s.supplierCode ?? '').trim()).filter(Boolean));

  const plan: Array<{ kind: 'customer' | 'supplier'; id: string; name: string; code: string; from: 'xero' | 'generated' }> = [];
  for (const c of missingC) {
    const fromXero = c.xeroId ? String(xeroByContactId.get(c.xeroId) ?? '').trim() : '';
    const useXero = fromXero && !takenC.has(fromXero);
    const code = useXero ? fromXero : nextCode(prefixOf('C', c.name), takenC);
    takenC.add(code);
    plan.push({ kind: 'customer', id: c.id, name: c.name, code, from: useXero ? 'xero' : 'generated' });
  }
  for (const s of missingS) {
    const fromXero = s.xeroId ? String(xeroByContactId.get(s.xeroId) ?? '').trim() : '';
    const useXero = fromXero && !takenS.has(fromXero);
    const code = useXero ? fromXero : nextCode(prefixOf('S', s.name), takenS);
    takenS.add(code);
    plan.push({ kind: 'supplier', id: s.id, name: s.name, code, from: useXero ? 'xero' : 'generated' });
  }

  if (plan.length) {
    const fromXeroCount = plan.filter((p) => p.from === 'xero').length;
    console.log(`  would assign ${plan.length}: ${fromXeroCount} taken from Xero's AccountNumber, ${plan.length - fromXeroCount} generated`);
    console.log(`\n  ${'Code'.padEnd(10)}${'Source'.padEnd(11)}${'Kind'.padEnd(10)}Name`);
    for (const p of plan.slice(0, SHOW))
      console.log(`  ${p.code.padEnd(10)}${p.from.padEnd(11)}${p.kind.padEnd(10)}${p.name.slice(0, 48)}`);
    if (plan.length > SHOW) console.log(`  … and ${plan.length - SHOW} more`);
  }

  if (!APPLY || !plan.length) return plan.length;

  let ok = 0;
  for (const p of plan) {
    try {
      if (p.kind === 'customer')
        await prisma.customer.update({ where: { id: p.id }, data: { customerCode: p.code } });
      else await prisma.supplier.update({ where: { id: p.id }, data: { supplierCode: p.code } });
      ok++;
    } catch (e: any) {
      console.warn(`  ⚠ ${p.kind} ${p.name}: ${String(e.message).slice(0, 120)}`);
    }
  }
  console.log(`  ${ok}/${plan.length} codes written.`);
  return plan.length;
}

(async () => {
  // Xero's AccountNumber per ContactID — the real codes, so the backfill can
  // match what the client already reads in Xero instead of inventing one.
  const xeroByContactId = new Map<string, string>();
  if (!NO_XERO) {
    const tokens = await getXeroTokens(prisma, ORG);
    for (let page = 1; ; page++) {
      const j: any = await xeroGet(tokens, '/Contacts', { page });
      const list = j?.Contacts || [];
      for (const c of list) if (c.AccountNumber) xeroByContactId.set(String(c.ContactID), String(c.AccountNumber));
      process.stdout.write(`\r  Xero contacts page ${page}: ${xeroByContactId.size} with an AccountNumber   `);
      if (list.length < 100) break;
    }
    console.log('\n');
  }

  let total = 0;
  if (ALL_ORGS) {
    const orgs = await prisma.organization.findMany({ select: { id: true, name: true }, orderBy: { name: 'asc' } });
    for (const o of orgs) total += await sweepOrg(o.id, o.name, xeroByContactId);
  } else {
    const o = await prisma.organization.findUnique({ where: { id: ORG }, select: { name: true } });
    total = await sweepOrg(ORG, o?.name || ORG, xeroByContactId);
  }

  console.log(
    APPLY
      ? `\nDone. ${total} contact(s) processed.\n`
      : `\nDRY RUN — ${total} contact(s) would be given a code. Re-run with --apply to write them.\n`,
  );
  await prisma.$disconnect();
})().catch(async (e) => {
  console.error('ERR', e?.message || e);
  await prisma.$disconnect().catch(() => {});
  process.exit(1);
});
